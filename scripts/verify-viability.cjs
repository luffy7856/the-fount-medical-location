const assert=require('node:assert/strict');
const fs=require('node:fs');const ts=require('typescript');
require.extensions['.ts']=(m,file)=>m._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,file);
const {calculateViability,viabilityGate,VIABILITY_DEFAULTS:defaults,distanceDecay}=require('../src/data/viability-engine.ts');
const {modelFor}=require('../src/data/viability-models.ts');
const model=modelFor('피부과');
const a={...defaults,targetPopulation:10000,monthlyUtilization:.2,retention:1,catchmentFactor:1,fixedCostWon:32000000,revenuePerVisitWon:80000,monthlyCapacity:10000};
const c=[{id:'a',name:'A',travelMinutes:10,attraction:1,evidence:'assumption'}];
const r=calculateViability(a,c,model);
assert.equal(r.marketVisits,2000);assert(r.share>0&&r.share<1);assert.equal(r.visits,r.marketVisits*r.share);
assert.equal(r.bepVisits,500);assert.equal(r.revenueWon,r.visits*80000);
assert(r.scoreParts&&Object.keys(r.scoreParts).length===6);
assert(Number.isInteger(r.score));
assert(Math.abs(r.share+r.outsideShare+r.competitors.reduce((s,c)=>s+c.share,0)-1)<1e-9);
assert.equal(calculateViability({...a,targetPopulation:0},c,model).score,0);
assert(calculateViability({...a,targetPopulation:100},[],model).score<=40);
assert(calculateViability({...a,fixedCostWon:1e9},c,model).score<=40);
assert.equal(calculateViability({...a,variableRate:1},c,model).score,null);
assert.equal(calculateViability({...a,revenuePerVisitWon:0},c,model).bepVisits,null);
assert.equal(calculateViability({...a,monthlyCapacity:5},c,model).high,5);
assert(calculateViability({...a,riskMultiplier:.5},c,model).score<r.score);
assert.equal(calculateViability({...a,retention:0,inflowVisits:0},c,model).visits,0);
const inflowOnly=calculateViability({...a,retention:0,inflowVisits:300},c,model);
assert(inflowOnly.visits>0&&inflowOnly.visits<300);
assert(calculateViability(a,[...c,{...c[0],id:'b'}],model).visits<r.visits);
const dense=Array.from({length:194},(_,index)=>({id:`d${index}`,name:`D${index}`,travelMinutes:8,attraction:1,evidence:'observed'}));
const isolatedDense=calculateViability({...a,targetPopulation:26490,inflowVisits:0},dense,model);
const clusteredDense=calculateViability({...a,targetPopulation:26490,inflowVisits:1300,clusterDemandMultiplier:2.5,competitionSensitivity:.55},dense,model);
assert(clusteredDense.visits>isolatedDense.visits*2);
assert(clusteredDense.rawCompetitorPower>clusteredDense.effectiveCompetitorPower);
assert(clusteredDense.score>0);
const funded=calculateViability({...a,startupCapitalWon:500000000,monthlyRentWon:7000000,monthlyDebtPrincipalWon:5000000},c,model);
const overfunded=calculateViability({...a,startupCapitalWon:1500000000,monthlyRentWon:7000000,monthlyDebtPrincipalWon:5000000},c,model);
assert(funded.paybackMonths>0);assert(overfunded.score<funded.score);
assert(funded.lowCoverage<funded.coverage);assert(funded.scoreParts.downside<funded.scoreParts.breakEven);
assert.deepEqual([.599,.6,.799,.8,.999,1,1.199,1.2].map(viabilityGate),[40,60,60,75,75,90,90,100]);
assert.equal(distanceDecay(31,model.decay),0);
for(const decay of [[],[{minutes:10,factor:1.1}],[{minutes:20,factor:.5},{minutes:10,factor:.2}],[{minutes:10,factor:.5},{minutes:20,factor:.8}],[{minutes:10,factor:NaN}]])assert.throws(()=>calculateViability(a,c,{...model,decay}));
assert.throws(()=>calculateViability(a,[...c,...c],model));
assert.throws(()=>calculateViability(a,c,{...model,version:''}));
for(const key of ['targetPopulation','monthlyUtilization','fixedCostWon'])assert.throws(()=>calculateViability({...a,[key]:NaN},c,model));
console.log('PASS: composite score, cluster attraction, saturated competition, break-even, downside, margin, payback, rent and debt');
