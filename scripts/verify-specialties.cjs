const fs = require('node:fs');
const assert = require('node:assert/strict');
const Module = require('node:module');
const ts = require('typescript');
const file = require('node:path').join(__dirname, '../src/data/specialties.ts');
const compiled = new Module(file);
compiled._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, file);
const {matchesSpecialty: matches, specialties} = compiled.exports;
assert(specialties.includes('비뇨기과'));
assert(matches('서울비뇨기과의원', '', '비뇨기과'));
assert(matches('서울의원', '의료 > 비뇨의학과', '비뇨기과'));
assert(matches('Clinic', 'urology', '비뇨기과'));
assert(!matches('서울피부과', '피부과', '비뇨기과'));
assert(matches('서울의원', '피부과', '피부과'));
assert(!matches('서울내과', '내과', '피부과'));
assert(!matches('서울치과', '치과', '피부과'));
assert(!matches('종합병원', '병원', '피부과'));
assert(matches('종합병원', '병원', '기타'));
console.log('PASS: specialty list, urology aliases, unrelated specialties excluded, unknown category excluded');
